#K-Fold Cross Validation
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.metrics import roc_curve, auc

# Define Stratified 5-Fold split
skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
model = RandomForestClassifier(n_estimators=100, max_depth=5, random_state=42)

# Calculate Cross-Validation Accuracy and ROC-AUC
cv_acc = cross_val_score(model, X_train, y_train, cv=skf, scoring='accuracy')
cv_auc = cross_val_score(model, X_train, y_train, cv=skf, scoring='roc_auc')

print(f"Mean CV Accuracy: {cv_acc.mean():.4f} ± {cv_acc.std():.4f}")
print(f"Mean CV ROC-AUC:   {cv_auc.mean():.4f} ± {cv_auc.std():.4f}")

plt.figure(figsize=(9, 6))

tprs = []
aucs = []
mean_fpr = np.linspace(0, 1, 100)

for fold, (train_idx, val_idx) in enumerate(skf.split(X_train, y_train)):
    X_tr, y_tr = X_train.iloc[train_idx], y_train.iloc[train_idx]
    X_val, y_val = X_train.iloc[val_idx], y_train.iloc[val_idx]

    # Train model and predict probabilities
    model.fit(X_tr, y_tr)
    y_proba = model.predict_proba(X_val)[:, 1]

    # Compute ROC curve metrics
    fpr, tpr, _ = roc_curve(y_val, y_proba)
    roc_auc = auc(fpr, tpr)
    aucs.append(roc_auc)

    # Interpolate TPR to align across folds
    interp_tpr = np.interp(mean_fpr, fpr, tpr)
    interp_tpr[0] = 0.0
    tprs.append(interp_tpr)

    plt.plot(fpr, tpr, lw=1, alpha=0.35, label=f'Fold {fold + 1} (AUC = {roc_auc:.3f})')

# Random Guessing Baseline
plt.plot([0, 1], [0, 1], linestyle='--', lw=2, color='red', label='Chance (AUC = 0.500)', alpha=0.8)

# Calculate Mean ROC curve and Standard Deviation
mean_tpr = np.mean(tprs, axis=0)
mean_tpr[-1] = 1.0
mean_auc = auc(mean_fpr, mean_tpr)
std_auc = np.std(aucs)

plt.plot(mean_fpr, mean_tpr, color='blue', label=f'Mean ROC (AUC = {mean_auc:.3f} ± {std_auc:.3f})', lw=2.5)

# Standard deviation band
std_tpr = np.std(tprs, axis=0)
tprs_upper = np.minimum(mean_tpr + std_tpr, 1)
tprs_lower = np.maximum(mean_tpr - std_tpr, 0)
plt.fill_between(mean_fpr, tprs_lower, tprs_upper, color='grey', alpha=0.2, label=r'± 1 std. dev.')

plt.xlim([-0.05, 1.05])
plt.ylim([-0.05, 1.05])
plt.xlabel('False Positive Rate (1 - Specificity)')
plt.ylabel('True Positive Rate (Sensitivity)')
plt.title('5-Fold Cross-Validation ROC-AUC Curve (Titanic Dataset)', fontsize=13, fontweight='bold')
plt.legend(loc="lower right")
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()